function parseMessage(content) {
  const parts = [], pr = /\[PROFILE_SUMMARY_START\]([\s\S]*?)\[PROFILE_SUMMARY_END\]/g
  let pm, last = 0, blocks = []
  while ((pm = pr.exec(content)) !== null) blocks.push({ i:pm.index, full:pm[0], inner:pm[1].trim() })
  if (!blocks.length) return parseTextCode(content)
  for (const b of blocks) {
    if (b.i > last) parts.push(...parseTextCode(content.slice(last, b.i)))
    parts.push({ type:'profile', content:b.inner })
    last = b.i + b.full.length
  }
  if (last < content.length) parts.push(...parseTextCode(content.slice(last)))
  return parts
}
function parseTextCode(text) {
  const parts = [], re = /```(?:\w+)?\n?([\s\S]*?)```/g
  let m, last = 0
  while ((m = re.exec(text)) !== null) {
    if (m.index > last) parts.push({ type:'text', content:text.slice(last, m.index) })
    parts.push({ type:'code', content:m[1] })
    last = m.index + m[0].length
  }
  if (last < text.length) parts.push({ type:'text', content:text.slice(last) })
  return parts
}
function renderText(raw) {
  return raw.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;')
    .replace(/\*\*(.+?)\*\*/g,'<strong>$1</strong>').replace(/\*(.+?)\*/g,'<em>$1</em>')
}
